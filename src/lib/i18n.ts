export function translate(text: string, lang: 'ko' | 'en'): string {
  return lang === 'en' ? (EN[text] ?? text) : text;
}

export function useT() {
  const lang = useStore(settingsStore, (s) => s.language);
  return (text: string) => translate(text, lang);
}
